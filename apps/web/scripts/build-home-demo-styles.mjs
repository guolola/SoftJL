// Compiles the upstream theme/utilities inside a local scope so the platform shell keeps its own theme.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const root = fileURLToPath(new URL("../src/features/standard-project/components/home-demo/", import.meta.url));
let upstream = await fs.readFile(path.join(root, "source/styles/globals.css"), "utf8");
// Site-wide documentation plugins and page animations are outside the selected content area.
upstream = upstream.replace(/^@import.*$/gm, "").replace(/^@plugin.*$/gm, "").replace(/^@source.*$/gm, "");
// Shared composer controls also need scoped utilities so the homepage reset preserves their layout.
const sharedSources = [
  "switch.tsx", "modeling-composer.tsx", "modeling-composer-attachments.tsx",
  "modeling-model-selector.tsx", "model-selector.tsx", "model-selector-popover.tsx",
  "model-selector-command.tsx", "modeling-context-display.tsx",
  "badge.tsx", "card.tsx", "button.tsx",
];
const input = '@import "tailwindcss" source(none);\n@import "tw-animate-css";\n@import "./source/styles/shimmer.css";\n@source "./source";\n@source "./integration/reasoning-switch.tsx";\n'
  + sharedSources.map((file) => `@source "../../../../shared/ui/${file}";\n`).join("")
  + '@source "../../../../shared/lib/modeling-context-usage.ts";\n'
  + '@source "./integration/elements";\n@source "./integration/project-tools.tsx";\n'
  + '@source "./integration/project-thread-message.tsx";\n'
  + '@source "./integration/intro-entry.tsx";\n@source "./integration/intro";\n'
  + '@import "./integration/intro/orbit.css";\n'
  + upstream;
const compiled = await postcss([tailwind({ optimize: false })]).process(input, { from: path.join(root, "home-demo-input.css") });
const sheet = compiled.root;
// Source utilities must outrank the host application's unlayered component rules.
const scope = ".homepage-theme.homepage-theme.homepage-theme";
sheet.walkAtRules("layer", rule => { if (rule.nodes) rule.replaceWith(...rule.nodes); else rule.remove(); });
sheet.walkRules(rule => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  if (rule.selector.includes("&")) return; // Nested variants inherit the already scoped utility selector.
  rule.selector = postcss.list.comma(rule.selector).map(selector => {
    if ([":root", ":host", "html", "body"].includes(selector)) return scope;
    if (selector === ".dark") return `.dark ${scope}`;
    if (selector === "*") return `${scope}, ${scope} *`;
    return /^[.:]/.test(selector) ? `${scope}${selector}, ${scope} ${selector}` : `${scope} ${selector}`;
  }).join(",\n");
});
const hosting = `\n/* Font family names match the upstream next/font families, served from local packages. */
.homepage-theme { --font-public-sans: "Public Sans Variable", sans-serif; --font-jetbrains-mono: "JetBrains Mono Variable", monospace; font-family: var(--font-public-sans); -webkit-font-smoothing: antialiased; }
.homepage-conversation { flex: 1; }
`;
await fs.writeFile(path.join(root, "home-demo.css"), "/* Scoped assistant-ui homepage styles; generated by scripts/build-home-demo-styles.mjs from the supplied source. */\n" + sheet.toString() + hosting);
console.log(`Built isolated homepage styles (${sheet.nodes.length} source rules).`);

// Renders the requirement authoring page and coordinates rule editing, quality checks, and generation actions.
import { useEffect, useMemo, useRef, useState } from "react";
import { useTranslation } from "react-i18next";
import {
  AlertTriangle,
  RefreshCw,
  FileText,
  Network,
} from "lucide-react";
import { Button } from "../../../shared/ui/button";
import { FeedbackReopenButton, type FeedbackDialogState } from "../../../shared/ui/feedback-dialog";
import { Badge } from "../../../shared/ui/badge";
import {
  DIAGRAM_META,
  DIAGRAM_ORDER,
  getDiagramDescription,
  getDiagramLabel,
  type DiagramType,
} from "../../../entities/diagram/model";
import { useWorkspaceSession } from "../../workspace-session/state";
import { useWorkspaceShell } from "../../workspace-shell/state";
import {
  clearRequirementRuleRequest,
  pendingRequirementRuleRequest,
  PROJECT_REQUIREMENT_RULE_REQUEST_EVENT,
} from "../../../shared/lib/app-navigation";
import {
  buildRequirementModelRepairRecords,
  requirementTargetBlockReason,
  requirementTargetCardState,
  MISSING_USECASE_BLOCK_REASON,
  STALE_USECASE_BLOCK_REASON,
} from "../lib/requirement-target-view-model";
import { type AutoGeneratedUpstreamReview } from "../lib/requirement-review-view-model";
import { GenerationModelControls } from "../../workspace-session/components/generation-model-controls";
import { ModelingGenerationButton } from "../../../shared/ui/modeling-generation-button";
import {
  PageContainer,
  PageHeader,
} from "../../../shared/template/layout/page";
import {
  loadUserSettings,
  USER_SETTINGS_CHANGED_EVENT,
} from "../../../shared/lib/user-settings";
import {
  MobileCompactGrid,
} from "../../workspace-shell/components/mobile-density";
import { ModelBentoCard } from "../../workspace-shell/components/model-bento-card";
import { useModelCardStatus } from "../../workspace-shell/lib/use-model-card-status";
import {
  ALL_RULE_CATEGORIES,
  REQUIREMENT_RULES_PER_PAGE,
  RequirementRulesTable,
  type RequirementRuleCategoryFilter,
} from "./requirement-rules-table";
import { RequirementRuleDetailDialog } from "./requirement-rule-detail-dialog";
import {
  RequirementTraceabilityDialogs,
  type RequirementModelRepairResult,
} from "./requirement-traceability-dialogs";
import { NewRequirementRuleDialog } from "./new-requirement-rule-dialog";
import { RequirementComposer, type RequirementComposerOptions } from "./requirement-composer";
import { TargetSelectionActions } from "../../workspace-shell/components/target-selection-actions";
import { independentModelGenerationTargets, type RequirementRuleType } from "@uml-platform/contracts";
import { modelGenerationSelectionBlockReason } from "../../workspace-session/lib/model-generation-selection";
import { RequirementModelCardPopovers } from "./requirement-model-card-popovers";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "../../../shared/ui/dialog";
import { UpstreamWorkflowIllustration } from "../../workspace-shell/components/upstream-workflow-illustration";
import {
  REQUIREMENT_DIAGRAM_ICON,
  upstreamBaselineState,
  upstreamStateFromAvailability,
  type UpstreamInput,
  type UpstreamInputState,
} from "../../workspace-shell/lib/upstream-dependencies";

const REQUIREMENT_WORKFLOW_ID = "requirement-upstream-workflow";

export function TextRequirementView({
  view = "all",
}: {
  view?: "system" | "models" | "all";
}) {
  const { t } = useTranslation();
  const { openDiagram, openSystemRequirements } = useWorkspaceShell();
  const { requirementStatusFor } = useModelCardStatus();
  const {
    workspaceInitialized,
    requirementText,
    hasUncommittedRequirementDraft,
    inputScreening,
    inputScreeningError,
    setRequirementText,
    rules,
    models,
    createRequirementRule,
    updateRequirementRule,
    deleteRequirementRule,
    selectedDiagrams,
    setSelectedDiagrams,
    generating,
    generateRules,
    requirementGenerationRunId,
    cancelRequirementGeneration,
    generateDiagrams,
    isRulesStale,
    rulesStaleReason,
    staleDiagrams,
    generatedDiagrams,
    requirementModelTraceability,
    autoGeneratedUpstreamReviews,
    decideAutoGeneratedUpstreamReview,
    requirementBaseline,
    canUpdateWorkspace,
    canStartRuns,
    workspacePermissionReason,
    generationModelBlockedReason,
  } = useWorkspaceSession();
  const [query, setQuery] = useState("");
  const [showStaleBanner, setShowStaleBanner] = useState(
    () => loadUserSettings().showStaleBanner,
  );
  const [newRuleDialogOpen, setNewRuleDialogOpen] = useState(false);
  const [newRuleText, setNewRuleText] = useState("");
  const [newRuleType, setNewRuleType] = useState<RequirementRuleType>("functional");
  const [newRuleError, setNewRuleError] = useState<string | null>(null);
  const [modelRepairResult, setModelRepairResult] =
    useState<RequirementModelRepairResult | null>(null);
  const [detailRuleId, setDetailRuleId] = useState<string | null>(null);
  const [traceabilityDialogOpen, setTraceabilityDialogOpen] = useState(false);
  const [ruleReplacementDialogOpen, setRuleReplacementDialogOpen] =
    useState(false);
  const pendingRuleSubmission = useRef<{ options: RequirementComposerOptions; resolve: (accepted: boolean) => void } | null>(null);
  const [currentRulePage, setCurrentRulePage] = useState(1);
  const [rulePageSize, setRulePageSize] = useState(REQUIREMENT_RULES_PER_PAGE);
  const [ruleCategoryFilter, setRuleCategoryFilter] =
    useState<RequirementRuleCategoryFilter>(ALL_RULE_CATEGORIES);
  const [inspectedDiagram, setInspectedDiagram] = useState<DiagramType>(DIAGRAM_ORDER[0]);

  useEffect(() => {
    if (view === "models") return;
    const openRequestedRule = () => {
      const ruleId = pendingRequirementRuleRequest();
      if (!ruleId || !rules.some((rule) => rule.id === ruleId)) return;
      clearRequirementRuleRequest(ruleId);
      setRuleCategoryFilter(ALL_RULE_CATEGORIES);
      setQuery(ruleId);
      setCurrentRulePage(1);
      setDetailRuleId(ruleId);
    };
    openRequestedRule();
    window.addEventListener(PROJECT_REQUIREMENT_RULE_REQUEST_EVENT, openRequestedRule);
    return () => window.removeEventListener(PROJECT_REQUIREMENT_RULE_REQUEST_EVENT, openRequestedRule);
  }, [rules, view]);

  useEffect(() => {
    const syncSettings = () => {
      const settings = loadUserSettings();
      setShowStaleBanner(settings.showStaleBanner);
    };

    window.addEventListener(USER_SETTINGS_CHANGED_EVENT, syncSettings);
    return () => {
      window.removeEventListener(USER_SETTINGS_CHANGED_EVENT, syncSettings);
    };
  }, []);

  const hasGeneratedRules = rules.length > 0;
  const hasRequirementSourceText = requirementText.trim().length > 0;
  const canEditRequirements = canUpdateWorkspace;
  const canRunGeneration = canUpdateWorkspace && canStartRuns;
  const editBlockedReason =
    workspacePermissionReason ?? t("requirements.permissions.edit");
  const generationBlockedByPermissionReason =
    workspacePermissionReason ?? generationModelBlockedReason ?? t("requirements.permissions.run");

  useEffect(() => () => { pendingRuleSubmission.current?.resolve(false); }, []);

  const runGenerateRules = (options: RequirementComposerOptions = {}): Promise<boolean> => {
    if (!canRunGeneration || generationModelBlockedReason || generating) return Promise.resolve(false);
    if (hasGeneratedRules) {
      if (pendingRuleSubmission.current) return Promise.resolve(false);
      setRuleReplacementDialogOpen(true);
      return new Promise((resolve) => { pendingRuleSubmission.current = { options, resolve }; });
    }
    return generateRules(options);
  };

  const closeRuleReplacement = () => {
    pendingRuleSubmission.current?.resolve(false);
    pendingRuleSubmission.current = null;
    setRuleReplacementDialogOpen(false);
  };

  const confirmRuleReplacement = async () => {
    const pending = pendingRuleSubmission.current;
    pendingRuleSubmission.current = null;
    setRuleReplacementDialogOpen(false);
    if (!canRunGeneration || generationModelBlockedReason || generating) { pending?.resolve(false); return; }
    try {
      const accepted = await generateRules(pending?.options);
      pending?.resolve(accepted);
    } catch {
      pending?.resolve(false);
    }
  };

  const runGenerateDiagrams = (only?: DiagramType[]) => {
    if (!canRunGeneration || generationModelBlockedReason) return;
    void generateDiagrams(only);
  };

  const decideAutoReviews = (
    reviews: AutoGeneratedUpstreamReview[],
    decision: "accepted" | "dismissed",
  ) => {
    void Promise.all(
      reviews.map((review) =>
        decideAutoGeneratedUpstreamReview(review.id, decision),
      ),
    );
  };

  const locateRequirementRule = (ruleId: string) => {
    const element = document.getElementById(`rule-${ruleId}`);
    if (!element) return;
    element.scrollIntoView({ behavior: "smooth", block: "center" });
    element.classList.add("ring-2", "ring-primary/40");
    setTimeout(() => {
      element.classList.remove("ring-2", "ring-primary/40");
    }, 1200);
  };

  const selectableDiagramSet = useMemo(() => new Set(DIAGRAM_ORDER.filter((diagram) =>
    requirementTargetCardState({
      diagram, models, autoGeneratedUpstreamReviews, canEditRequirements, generatedDiagrams,
      hasRequirementSourceText: Boolean(requirementText.trim()), isRulesStale, rules, selectedDiagrams, staleDiagrams,
    }).canSelectDiagram,
  )), [models, autoGeneratedUpstreamReviews, canEditRequirements, generatedDiagrams, requirementText, isRulesStale, rules, selectedDiagrams, staleDiagrams]);

  const toggleDiagram = (diagram: DiagramType, checked: boolean) => {
    if (!canEditRequirements) return;
    if (checked && !selectableDiagramSet.has(diagram)) {
      return;
    }
    setSelectedDiagrams(
      checked
        ? Array.from(new Set([...selectedDiagrams, diagram]))
        : selectedDiagrams.filter((value) => value !== diagram),
    );
  };

  useEffect(() => {
    const nextSelectedDiagrams = independentModelGenerationTargets("requirements", selectedDiagrams.filter((diagram) =>
      DIAGRAM_ORDER.includes(diagram),
    ));
    if (nextSelectedDiagrams.length !== selectedDiagrams.length) {
      setSelectedDiagrams(nextSelectedDiagrams);
    }
  }, [selectedDiagrams, setSelectedDiagrams]);

  const resetNewRuleForm = () => {
    setNewRuleType("functional");
    setNewRuleText("");
    setNewRuleError(null);
  };

  const submitNewRule = () => {
    const trimmedText = newRuleText.trim();
    if (!trimmedText) {
      setNewRuleError(t("requirements.validation.textRequired"));
      return;
    }
    if (!canEditRequirements || generating) return;
    createRequirementRule({
      type: newRuleType,
      text: trimmedText,
    });
    setNewRuleDialogOpen(false);
    resetNewRuleForm();
  };

  const newRuleCanSubmit = newRuleText.trim().length > 0;

  const filteredRules = useMemo(() => {
    const normalizedQuery = query.trim().toLowerCase();
    return rules.filter((rule) => {
      const matchesQuery =
        !normalizedQuery || rule.id.toLowerCase().includes(normalizedQuery) ||
        rule.text.toLowerCase().includes(normalizedQuery);
      const matchesCategory =
        ruleCategoryFilter === ALL_RULE_CATEGORIES ||
        rule.type === ruleCategoryFilter;
      return matchesQuery && matchesCategory;
    });
  }, [rules, query, ruleCategoryFilter]);

  useEffect(() => {
    setCurrentRulePage(1);
  }, [query, ruleCategoryFilter]);

  const totalRulePages = Math.max(1, Math.ceil(filteredRules.length / rulePageSize));
  const safeRulePage = Math.min(currentRulePage, totalRulePages);
  const firstRuleIndex =
    filteredRules.length === 0 ? 0 : (safeRulePage - 1) * rulePageSize + 1;
  const lastRuleIndex = Math.min(filteredRules.length, safeRulePage * rulePageSize);
  const pagedRules = filteredRules.slice(firstRuleIndex - 1, lastRuleIndex);
  const detailRule = rules.find(rule => rule.id === detailRuleId) ?? null;
  const emptyRuleSlots = Math.max(0, rulePageSize - pagedRules.length);
  useEffect(() => {
    if (currentRulePage > totalRulePages) {
      setCurrentRulePage(totalRulePages);
    }
  }, [currentRulePage, totalRulePages]);

  // The draft notice names the button the user actually sees.
  const rulesActionLabel = t(isRulesStale || hasUncommittedRequirementDraft && rules.length > 0
    ? "requirements.source.updateRules" : "requirements.source.startAnalysis");
  const draftNotice = t("requirements.source.draftNotice", {
    action: rulesActionLabel,
  });
  const rulesStaleMessage =
    hasUncommittedRequirementDraft
      ? draftNotice
      : rulesStaleReason === "rules"
      ? t("requirements.stale.downstream")
      : rulesStaleReason === "source-missing"
        ? t("requirements.stale.empty")
        : t("requirements.stale.changed");
  const staleDiagramReason =
    isRulesStale && rulesStaleReason === "text"
      ? t("requirements.stale.changedTitle")
      : rulesStaleReason === "source-missing"
        ? t("requirements.stale.emptyTitle")
      : t("requirements.stale.reviewTitle");
  const selectedTargetBlockReason =
    selectedDiagrams
      .map((diagram) =>
        requirementTargetBlockReason({
          diagram,
          models,
          generatedDiagrams,
          hasRequirementSourceText,
          isRulesStale,
          rules,
          staleDiagrams,
          selectedDiagrams,
        }),
      )
      .find(Boolean) ?? null;
  const missingRequirementSourceReason = !hasRequirementSourceText && rules.length === 0
    ? requirementTargetBlockReason({
        diagram: "usecase",
        models,
        generatedDiagrams,
        hasRequirementSourceText,
        isRulesStale,
        rules,
        staleDiagrams,
      })
    : null;
  const modelGenerationBlockedReason = view === "system" ? null
    : !canRunGeneration ? workspacePermissionReason ?? t("requirements.permissions.run")
      : hasUncommittedRequirementDraft ? t("requirements.source.draftGenerationBlocked")
        : selectedTargetBlockReason ?? missingRequirementSourceReason ?? generationModelBlockedReason;
  const pageNoticeMessages = [
    !canEditRequirements ? editBlockedReason : null,
    view !== "models" && showStaleBanner && isRulesStale && !hasUncommittedRequirementDraft ? rulesStaleMessage : null,
    view !== "system" && showStaleBanner && staleDiagrams.length > 0
      ? `${t("requirements.stale.modelCount", { count: staleDiagrams.length, reason: staleDiagramReason })}${staleDiagrams.map((diagram) => getDiagramLabel(diagram, t)).join(t("traceability.refSeparator"))}`
      : null,
    modelGenerationBlockedReason,
  ].filter((message): message is string => Boolean(message));
  const uniquePageNoticeMessages = [...new Set(pageNoticeMessages)];
  const usecaseBlocked = modelGenerationBlockedReason === STALE_USECASE_BLOCK_REASON ||
    modelGenerationBlockedReason === MISSING_USECASE_BLOCK_REASON;
  const modelGuidanceAction = view !== "system" && modelGenerationBlockedReason && canRunGeneration
    ? usecaseBlocked
      ? { label: t("feedback.actions.requirementModels"), onSelect: () => openDiagram("usecase") }
      : selectedTargetBlockReason || missingRequirementSourceReason
        ? { label: t("requirements.sourceAction"), onSelect: openSystemRequirements }
        : undefined
    : undefined;
  const pageFeedback: FeedbackDialogState | null = pageNoticeMessages.length > 0 ? {
    dedupeKey: `requirements:${view}:notices`,
    revision: uniquePageNoticeMessages.join("|"),
    tone: "warning",
    title: modelGenerationBlockedReason ? t("requirements.modelBlockedTitle") : t("feedback.needsAttentionCount", { count: uniquePageNoticeMessages.length }),
    message: uniquePageNoticeMessages.join("\n"),
    primaryAction: modelGuidanceAction,
    keepReopenEntry: true,
  } : null;
  const inspectedRules = rules;
  const plannedRequirementDiagrams = selectedDiagrams.filter(diagram => selectableDiagramSet.has(diagram));
  const resolveUpstreamState = (input: UpstreamInput): UpstreamInputState => {
    switch (input.kind) {
      case "rules": return upstreamStateFromAvailability(inspectedRules.length > 0, isRulesStale);
      case "baseline": return upstreamBaselineState(requirementBaseline, isRulesStale);
      case "requirement": {
        const status = requirementStatusFor(input.diagram);
        const planned = plannedRequirementDiagrams.includes(input.diagram) || status === "queued";
        // The source can be current itself while an existing analysis still uses its previous event flows.
        const changedAnalysisSource = input.eventFlows === "single-use-case" &&
          (planned || staleDiagrams.includes("analysis"));
        return upstreamStateFromAvailability(Object.values(models).some(model => model?.diagramKind === input.diagram), staleDiagrams.includes(input.diagram) || changedAnalysisSource, {
          planned: !changedAnalysisSource && planned,
          running: status === "running",
        });
      }
      default: return "missing";
    }
  };
  const requirementModelRepairRecords = useMemo(() => {
    return buildRequirementModelRepairRecords({
      generatedDiagrams,
      requirementModelTraceability,
      rules,
    });
  }, [generatedDiagrams, requirementModelTraceability, rules]);

  const renderRequirementInput = (mode: "empty" | "generated") => {
    // Keep the input mounted when loaded rules change the surrounding section presentation.
    return <div className="relative flex flex-col">
      <div className="relative flex items-center justify-between gap-4">
        <div className="flex items-center gap-2">
          <FileText className="size-5 text-primary" />
          <h2
            id="requirement-text-heading"
            className="text-xl font-semibold tracking-normal text-foreground"
          >
            {mode === "empty" ? t("requirements.source.projectDescription") : t("requirements.source.description")}
          </h2>
        </div>
      </div>
      <p id="requirement-text-guidance" className="sr-only">
        {t("requirements.source.guidance")}
      </p>
      <p id="requirement-text-capability" className="mt-1 text-sm leading-relaxed text-muted-foreground">
        {t("requirements.source.capability")}
      </p>
      <RequirementComposer
        text={requirementText}
        initialized={workspaceInitialized}
        hasUncommittedDraft={hasUncommittedRequirementDraft}
        disabled={!canEditRequirements}
        submitDisabled={!canRunGeneration || Boolean(generationModelBlockedReason)}
        running={generating}
        canCancel={Boolean(requirementGenerationRunId) && canRunGeneration}
        compact={mode === "generated"}
        submitLabel={rulesActionLabel}
        descriptionId="requirement-text-guidance requirement-text-capability"
        onTextChange={setRequirementText}
        onSubmit={runGenerateRules}
        onCancel={cancelRequirementGeneration}
      />
      {hasUncommittedRequirementDraft && (
        <p className="mt-2 text-sm text-warning" role="status">
          {draftNotice}
        </p>
      )}
      {inputScreeningError && (
        <p role="alert" className="mt-2 text-sm text-destructive">
          {t("requirements.source.screeningErrorTitle")}：{inputScreeningError}
        </p>
      )}
      {inputScreening && inputScreening.ignoredSpans.length > 0 && (
        <div className="mt-2 rounded-md border border-warning/40 bg-warning/5 px-3 py-2 text-sm" aria-live="polite">
          <p className="font-medium">{t("requirements.source.ignoredTitle")}：{t("requirements.source.ignoredSummary", { count: inputScreening.ignoredSpans.length })}</p>
          <ul className="mt-1 list-inside list-disc">
            {inputScreening.ignoredSpans.slice(0, 5).map((span) => (
              <li key={`${span.startOffset}-${span.endOffset}`} className="break-words">
                {requirementText.slice(span.startOffset, span.endOffset).slice(0, 180)}
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>;
  };

  const renderRequirementRules = () => (
    <div className="grid gap-4">
    <RequirementRulesTable
      canEditRequirements={canEditRequirements}
      deleteRequirementRule={deleteRequirementRule}
      editBlockedReason={editBlockedReason}
      emptyRuleSlots={emptyRuleSlots}
      filteredRules={filteredRules}
      firstRuleIndex={firstRuleIndex}
      generating={generating}
      onAddRule={() => setNewRuleDialogOpen(true)}
      onViewRule={setDetailRuleId}
      pagedRules={pagedRules}
      query={query}
      ruleCategoryFilter={ruleCategoryFilter}
      rulePageSize={rulePageSize}
      rulesCount={rules.length}
      safeRulePage={safeRulePage}
      setCurrentRulePage={setCurrentRulePage}
      setQuery={setQuery}
      setRuleCategoryFilter={setRuleCategoryFilter}
      setRulePageSize={setRulePageSize}
      totalRulePages={totalRulePages}
      updateRequirementRule={updateRequirementRule}
    />
    </div>
  );

  return (
    <div className="flex min-h-0 min-w-0 max-w-full flex-col overflow-x-clip bg-background">
      {view !== "models" && showStaleBanner && isRulesStale && !hasUncommittedRequirementDraft && (
        <div className="flex items-center gap-2 px-3 py-2 text-sm text-warning">
          <span>{rulesStaleMessage}</span>
          <Button
            size="sm"
            variant="outline"
            className="ml-auto h-7"
            onClick={() => { void runGenerateRules(); }}
            disabled={generating || !canRunGeneration || Boolean(generationModelBlockedReason)}
            title={(!canRunGeneration || generationModelBlockedReason) ? generationBlockedByPermissionReason : undefined}
          >
            <RefreshCw className="size-3.5" /> {t("requirements.source.regenerateRules")}
          </Button>
        </div>
      )}

      <PageContainer className="flex flex-col gap-5">
          <PageHeader
            title={
              view === "system"
                ? t("requirements.page.systemTitle")
                : view === "models"
                  ? t("requirements.page.modelsTitle")
                  : t("requirements.page.allTitle")
            }
            description={
              view === "system"
                ? t("requirements.page.systemDescription")
                : view === "models"
                  ? t("requirements.page.modelsDescription")
                  : t("requirements.page.allDescription")
            }
            notice={pageFeedback ? <FeedbackReopenButton feedback={pageFeedback} label={t("feedback.needsAttentionCount", { count: uniquePageNoticeMessages.length })} /> : null}
          />
          {!canEditRequirements && (
            <p role="status" className="inline-flex max-w-3xl items-center gap-2 text-xs text-warning">
              <AlertTriangle className="size-3.5" />
              {editBlockedReason}
            </p>
          )}
          {view !== "models" && <div className="grid min-w-0 max-w-full grid-cols-1 gap-4 overflow-x-hidden">
            <div className="grid min-w-0 grid-cols-[minmax(0,1fr)] gap-4">
              {renderRequirementInput(hasGeneratedRules ? "generated" : "empty")}
              {hasGeneratedRules && renderRequirementRules()}
            </div>
          </div>}

          {view !== "system" && <section id="requirement-target-models" className="flex min-w-0 flex-col gap-4">
            <div className="flex min-w-0 flex-col items-stretch gap-3 sm:flex-row sm:items-center sm:justify-between sm:gap-2">
              <div className="flex min-w-0 flex-wrap items-center gap-2">
                <Network className="size-5 text-primary" />
                <h2 className="text-xl font-semibold tracking-normal text-foreground">
                  {t("requirements.targetModels")}
                </h2>
                <Badge
                  variant="secondary"
                  className="border-0 px-3 py-1 font-mono text-xs"
                >
                  {selectedDiagrams.length}/{DIAGRAM_ORDER.length}
                </Badge>
                <TargetSelectionActions
                  disabled={generating || !canEditRequirements}
                  onSelectAll={() => setSelectedDiagrams(independentModelGenerationTargets("requirements", [...selectedDiagrams, ...DIAGRAM_ORDER].filter((diagram) => selectableDiagramSet.has(diagram))))}
                  onClear={() => setSelectedDiagrams([])}
                />
              </div>
              <div className="flex min-w-0 flex-nowrap items-center gap-2 overflow-x-auto pb-1 sm:shrink-0 sm:overflow-visible sm:pb-0">
                <GenerationModelControls disabled={!canRunGeneration || generating} />
                <ModelingGenerationButton
                  label={t("common.generate")}
                  busy={generating}
                  onClick={() => runGenerateDiagrams()}
                  disabled={
                    selectedDiagrams.length === 0 ||
                    generating ||
                    hasUncommittedRequirementDraft ||
                    Boolean(selectedTargetBlockReason) ||
                    !canRunGeneration || Boolean(generationModelBlockedReason)
                  }
                  title={
                    modelGenerationBlockedReason ?? undefined
                  }
                />
              </div>
            </div>
            {modelGenerationBlockedReason && <p role="status" className="text-xs text-muted-foreground">{modelGenerationBlockedReason}</p>}
            <MobileCompactGrid
              minWidth={720}
              variant="model-targets"
            >
              {DIAGRAM_ORDER.map((diagram) => {
                const meta = DIAGRAM_META[diagram];
                const localizedLabel = getDiagramLabel(diagram, t);
                const localizedDescription = getDiagramDescription(diagram, t);
                const {
                  autoFillLabels,
                  blockReason,
                  canSelectDiagram,
                  checked,
                  hasPendingAutoReview,
                  isAnalysisDiagram,
                  linkedRules,
                  pendingAutoReviews,
                  sourceCount,
                } = requirementTargetCardState({
                  models,
                  autoGeneratedUpstreamReviews,
                  canEditRequirements,
                  diagram,
                  generatedDiagrams,
                  hasRequirementSourceText,
                  isRulesStale,
                  rules,
                  selectedDiagrams,
                  staleDiagrams,
                });
                const localizedAutoFillLabels = autoFillLabels.map((label) =>
                  label === DIAGRAM_META.usecase.label
                    ? getDiagramLabel("usecase", t)
                    : label === "需求规则"
                      ? t("requirements.autoFillSources.rules")
                      : t("requirements.autoFillSources.mapping"),
                );
                const DiagramIcon = REQUIREMENT_DIAGRAM_ICON[diagram];
                return (
                  <ModelBentoCard
                    key={diagram}
                    label={localizedLabel}
                    english={meta.english}
                    description={localizedDescription}
                    singleLineDescription={isAnalysisDiagram}
                    icon={DiagramIcon}
                    categoryColorIndex={DIAGRAM_ORDER.indexOf(diagram)}
                    selected={checked}
                    disabled={!canSelectDiagram}
                    blockedReason={!canSelectDiagram ? blockReason ?? (isAnalysisDiagram
                      ? t("requirements.useCaseRequired") : t("requirements.rulesRequired")) : undefined}
                    countLabel={isAnalysisDiagram ? t("uxReview.sourceModels", { count: sourceCount }) : undefined}
                    pendingReview={hasPendingAutoReview}
                    title={
                      !canEditRequirements ? editBlockedReason : undefined
                    }
                    ariaLabel={t(checked ? "requirements.cancelSelect" : "requirements.select", { label: localizedLabel })}
                    checkboxLabel={localizedLabel}
                    onSelectedChange={(value) => toggleDiagram(diagram, value)}
                    status={requirementStatusFor(diagram)}
                    inspected={inspectedDiagram === diagram}
                    onInspect={() => setInspectedDiagram(diagram)}
                    content={
                      <div className="space-y-1.5">
                        {modelGenerationSelectionBlockReason("requirements", diagram, selectedDiagrams) &&
                          <p className="text-warning">{blockReason}</p>}
                        {isAnalysisDiagram &&
                          canSelectDiagram &&
                          linkedRules.length === 0 && (
                            <div className="min-w-0 truncate text-muted-foreground" title={t("requirements.analysisDependency")}>
                              {t("requirements.analysisDependency")}
                            </div>
                          )}
                        <RequirementModelCardPopovers
                          diagram={diagram}
                          autoFillLabels={blockReason ? [] : localizedAutoFillLabels}
                          label={localizedLabel}
                          linkedRules={linkedRules}
                          pendingAutoReviews={pendingAutoReviews}
                          onDecideAutoReviews={decideAutoReviews}
                          onLocateRule={locateRequirementRule}
                          showRuleLocations={view !== "models"}
                        />
                      </div>
                    }
                  />
                );
              })}
            </MobileCompactGrid>
          </section>}
          {view !== "system" && <UpstreamWorkflowIllustration
            id={REQUIREMENT_WORKFLOW_ID}
            stage="requirement"
            target={inspectedDiagram}
            targetLabel={getDiagramLabel(inspectedDiagram, t)}
            targetEnglish={DIAGRAM_META[inspectedDiagram].english}
            targetIcon={REQUIREMENT_DIAGRAM_ICON[inspectedDiagram]}
            targetColorIndex={DIAGRAM_ORDER.indexOf(inspectedDiagram)}
            rules={inspectedRules}
            resolveState={resolveUpstreamState}
          />}
      </PageContainer>

      {view !== "models" && <RequirementRuleDetailDialog
        canEdit={canEditRequirements && !generating}
        onSave={(id, patch) => { if (canEditRequirements && !generating) updateRequirementRule(id, patch); }}
        rule={detailRule}

        onOpenChange={(open) => {
          if (!open) setDetailRuleId(null);
        }}
      />}

      <RequirementTraceabilityDialogs
        modelRepairResult={modelRepairResult}
        records={requirementModelRepairRecords}
        setModelRepairResult={setModelRepairResult}
        setTraceabilityDialogOpen={setTraceabilityDialogOpen}
        traceabilityDialogOpen={traceabilityDialogOpen}
      />

      {view !== "models" && <Dialog
        open={ruleReplacementDialogOpen}
        onOpenChange={(open) => { if (!open) closeRuleReplacement(); }}
      >
        <DialogContent className="sm:max-w-lg">
          <DialogHeader>
            <DialogTitle>{t("requirements.replace.title")}</DialogTitle>
            <DialogDescription>
              {t("requirements.replace.description", { count: rules.length })}
            </DialogDescription>
          </DialogHeader>
          <DialogFooter className="gap-2 sm:gap-2">
            <Button
              type="button"
              variant="outline"
              onClick={closeRuleReplacement}
            >
              {t("requirements.replace.cancel")}
            </Button>
            <Button
              type="button"
              onClick={confirmRuleReplacement}
              disabled={generating || !canRunGeneration || Boolean(generationModelBlockedReason)}
            >
              {t("requirements.replace.confirm")}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>}

      {view !== "models" && <NewRequirementRuleDialog
        type={newRuleType}
        onTypeChange={setNewRuleType}
        canEditRequirements={canEditRequirements}
        generating={generating}
        newRuleCanSubmit={newRuleCanSubmit}
        newRuleError={newRuleError}
        newRuleText={newRuleText}
        onOpenChange={(open) => {
          setNewRuleDialogOpen(open);
          if (!open) resetNewRuleForm();
        }}
        onSubmit={submitNewRule}
        onTextChange={(text) => {
          setNewRuleText(text);
          setNewRuleError(null);
        }}
        open={newRuleDialogOpen}
      />}

    </div>
  );
}


// Verifies action labels describe only selected work, including regeneration of current models.
import { expect, it } from "vitest";
import { MISSING_USECASE_BLOCK_REASON, requirementTargetCardState } from "./requirement-target-view-model";
import { createRule } from "../../../../tests/helpers/workspace-test-utils";
import type { DiagramType } from "../../../entities/diagram/model";

it.each([{ rules: [] }])("shows missing rules inline without offering automatic rule completion", ({ rules }) => {
  const state = requirementTargetCardState({ models: {}, diagram: "class", rules, generatedDiagrams: [], selectedDiagrams: [],
    staleDiagrams: [], autoGeneratedUpstreamReviews: {}, canEditRequirements: true, hasRequirementSourceText: true, isRulesStale: false });
  expect(state.canSelectDiagram).toBe(false);
  expect(state.blockReason).toContain("请先添加或生成需求规则");
  expect(state.autoFillLabels).toEqual([]);
});

it("uses the fixed mapped rule set", () => {
  const state = requirementTargetCardState({ models: {}, diagram: "class", rules: [createRule({  })], generatedDiagrams: [], selectedDiagrams: [], staleDiagrams: [], autoGeneratedUpstreamReviews: {}, canEditRequirements: true, hasRequirementSourceText: true, isRulesStale: false });
  expect(state.canSelectDiagram).toBe(true);
  expect(state.sourceCount).toBe(1);
});

it("allows any real rule type as a model source", () => {
  const state = requirementTargetCardState({ models: {}, diagram: "class", rules: [createRule({ type: "interaction" })], generatedDiagrams: [], selectedDiagrams: [], staleDiagrams: [], autoGeneratedUpstreamReviews: {}, canEditRequirements: true, hasRequirementSourceText: true, isRulesStale: false });
  expect(state.canSelectDiagram).toBe(true);
  expect(state.blockReason).toBeNull();
  expect(state.sourceCount).toBe(1);
});

it.each<{ selectedDiagrams: DiagramType[] }>([
  { selectedDiagrams: [] }, { selectedDiagrams: ["usecase"] }, { selectedDiagrams: ["usecase", "analysis"] },
])("requires a saved usecase regardless of selection: $selectedDiagrams", ({ selectedDiagrams }) => {
  const state = requirementTargetCardState({
    diagram: "analysis", models: {}, rules: [createRule({ type: "functional" })],
    // A generated-kind receipt alone must not fabricate a missing source model.
    generatedDiagrams: ["usecase"], selectedDiagrams, staleDiagrams: [],
    autoGeneratedUpstreamReviews: {}, canEditRequirements: true, hasRequirementSourceText: true, isRulesStale: false,
  });
  expect(state.canSelectDiagram).toBe(false);
  expect(state.blockReason).toBe(MISSING_USECASE_BLOCK_REASON);
  expect(state.autoFillLabels).toEqual([]);
  expect(state.sourceCount).toBe(0);
});

it("enables analysis from an existing saved usecase model", () => {
  const state = requirementTargetCardState({
    diagram: "analysis", models: { "saved-usecase": {
      diagramKind: "usecase", title: "用例模型", summary: "用户查看订单", notes: [],
      actors: [], useCases: [], systemBoundaries: [], relationships: [],
    } }, rules: [createRule({ type: "functional" })], generatedDiagrams: ["usecase"], selectedDiagrams: [],
    staleDiagrams: [], autoGeneratedUpstreamReviews: {}, canEditRequirements: true, hasRequirementSourceText: true, isRulesStale: false,
  });
  expect(state.canSelectDiagram).toBe(true);
  expect(state.blockReason).toBeNull();
  expect(state.sourceCount).toBe(1);
});

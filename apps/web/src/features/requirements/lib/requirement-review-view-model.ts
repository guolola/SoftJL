// Field values, field-source labels and auto-review helpers for the requirement authoring UI.
// Rules have a single displayed state ("已生成"), so no row-status labels are derived here.
import type {
  AtomicRequirement,
  AtomicRequirementField,
} from "@uml-platform/contracts";
import type { DiagramType } from "../../../entities/diagram/model";
import type { WorkspaceRecord } from "../../../entities/workspace/model";
import type { TFunction } from "i18next";

export const REVIEWABLE_REQUIREMENT_FIELDS: AtomicRequirementField[] = [
  "actor",
  "subject",
  "action",
  "object",
  "condition",
  "outcome",
  "acceptanceCriteria",
];

export type AutoGeneratedUpstreamReview =
  WorkspaceRecord["autoGeneratedUpstreamReviews"][string];

export function stageRepairCopy(text: string) {
  return text.replace(/\bAI\b\s*/gu, "系统");
}

export function requirementFieldValue(
  requirement: AtomicRequirement,
  field: AtomicRequirementField,
) {
  const provenanceValue = requirement.fieldProvenance[field]?.value;
  if (typeof provenanceValue === "string" && provenanceValue.trim()) {
    return provenanceValue;
  }
  if (field === "acceptanceCriteria") {
    return requirement.acceptanceCriteria.join("；");
  }
  return requirement[field] ?? "";
}

export function requirementSourceLabel(source: string, t?: TFunction) {
  if (source === "ai-suggested") return t ? t("requirements.review.sources.ai") : "AI补齐";
  if (source === "manual") return t ? t("requirements.review.sources.manual") : "手动编辑";
  if (source === "source-text") return t ? t("requirements.review.sources.source") : "原文提取";
  return t ? t("requirements.review.sources.inferred") : "规则推断";
}

export function pendingAutoReviewsForRequirementDiagram(
  reviews: WorkspaceRecord["autoGeneratedUpstreamReviews"],
  diagram: DiagramType,
): AutoGeneratedUpstreamReview[] {
  return Object.values(reviews).filter(
    (review) =>
      review.status === "pending" &&
      ((review.artifactType === "requirement-model" &&
        review.artifactId === diagram) ||
        (review.artifactType === "requirement-rule" &&
          review.artifactId === `mapping:${diagram}`)),
  );
}

// Field values, field-source labels and auto-review helpers for the requirement authoring UI.
// Rules have a single displayed state ("已生成"), so no row-status labels are derived here.

import type { DiagramType } from "../../../entities/diagram/model";
import type { WorkspaceRecord } from "../../../entities/workspace/model";

export type AutoGeneratedUpstreamReview =
  WorkspaceRecord["autoGeneratedUpstreamReviews"][string];

export function stageRepairCopy(text: string) {
  return text.replace(/\bAI\b\s*/gu, "系统");
}

export function pendingAutoReviewsForRequirementDiagram(
  reviews: WorkspaceRecord["autoGeneratedUpstreamReviews"],
  diagram: DiagramType,
): AutoGeneratedUpstreamReview[] {
  return Object.values(reviews).filter(
    (review) =>
      review.status === "pending" &&
      ((review.artifactType === "requirement-model" &&
        review.artifactId === diagram) ||
        (review.artifactType === "requirement-rule" &&
          review.artifactId === `mapping:${diagram}`)),
  );
}

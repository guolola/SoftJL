// Defines the workspace repository contract shared by HTTP, mock, and React provider adapters.
import type { GenerationExecutionMode, UmlDiagramKind, DesignDiagramModelSpec, DesignRunSnapshot, DesignSvgArtifact, DiagramModelSpec, DocumentLibraryItem, DocumentRunSnapshot, RenderStructuredModelResponse, RunEventInput, RunSnapshot, SvgArtifact, FeasibilityRunSnapshot, FeasibilityInputs, FeasibilityImplementationPlan, ContextDiagramSpec, ContextTraceRow } from "@uml-platform/contracts";
import type { DiagramType } from "../../entities/diagram/model";
import type { ManualModelEditStatus, WorkspaceRecord } from "../../entities/workspace/model";
import type { RequirementRule } from "../../entities/requirement-rule/model";
import type { RunHistoryItem, RunHistorySnapshot } from "../../entities/run-history/index";

import type { StartDesignRunInput, StartDocumentRunInput, StartFeasibilityRunInput, StartRunInput } from "./start-inputs";

export interface RequirementRulesUpdateMetadata {
  sourceRunId?: string;
  requirementBaseline?: WorkspaceRecord["requirementBaseline"];
  requirementInputFingerprint?: string | null;
  requirementModelTraceability?: WorkspaceRecord["requirementModelTraceability"];

  rulesBasedOnTextVersion?: number | null;
  rulesVersion?: number;
}

// Recovery delivers snapshots independently of SSE events, including partial results.
export interface RunSubscriptionOptions<TSnapshot> {
  signal?: AbortSignal;
  onSnapshot?: (snapshot: TSnapshot) => void | Promise<void>;
}

export interface WorkspaceRepository {
  exportDiagram?(input: { diagramKind: UmlDiagramKind; plantUmlSource: string; format: "png" | "pdf" }, signal?: AbortSignal): Promise<Blob>;
  loadWorkspace(): Promise<WorkspaceRecord>;
  getProjectAccess?(): Promise<{
    capabilities: string[];
    generationExecutionMode?: GenerationExecutionMode;
  }>;

  updateFeasibility?(patch: Partial<{
    inputs: FeasibilityInputs;
    contextModel: ContextDiagramSpec | null;
    contextTraceability: ContextTraceRow[];
    contextPlantUml: string;
    contextSvg: string;
    contextFingerprint: string | null;
    implementationPlan: FeasibilityImplementationPlan | null;
    implementationFingerprint: string | null;
  }>): Promise<void>;
  startFeasibilityRun?(input: StartFeasibilityRunInput): Promise<{ runId: string }>;
  getFeasibilityRunSnapshot?(runId: string): Promise<FeasibilityRunSnapshot>;
  subscribeToFeasibilityRun?(
    runId: string,
    onEvent: (event: RunEventInput) => void,
    options?: RunSubscriptionOptions<FeasibilityRunSnapshot>,
  ): Promise<void>;
  updateRequirementRules?(
    rules: RequirementRule[],
    metadata?: RequirementRulesUpdateMetadata,
  ): Promise<void>;
  updateAutoGeneratedUpstreamReviews?(
    reviews: WorkspaceRecord["autoGeneratedUpstreamReviews"],
  ): Promise<void>;

  updateTestGenerationResult?(
    result: WorkspaceRecord["testGenerationResult"],
  ): Promise<void>;

startRun(input: StartRunInput): Promise<{ runId: string }>;
  cancelRun?(runId: string): Promise<void>;
  startDesignRun?(input: StartDesignRunInput): Promise<{ runId: string }>;

  startDocumentRun?(input: StartDocumentRunInput): Promise<{ runId: string }>;
  subscribeToRun(
    runId: string,
    onEvent: (event: RunEventInput) => void,
    options?: RunSubscriptionOptions<RunSnapshot>,
  ): Promise<void>;
  subscribeToDesignRun?(
    runId: string,
    onEvent: (event: RunEventInput) => void,
    options?: RunSubscriptionOptions<DesignRunSnapshot>,
  ): Promise<void>;

  subscribeToDocumentRun?(
    runId: string,
    onEvent: (event: RunEventInput) => void,
    options?: RunSubscriptionOptions<DocumentRunSnapshot>,
  ): Promise<void>;
  getRunSnapshot(runId: string): Promise<RunSnapshot>;
  getDesignRunSnapshot?(runId: string): Promise<DesignRunSnapshot>;

  getDocumentRunSnapshot?(runId: string): Promise<DocumentRunSnapshot>;
  listDocuments?(): Promise<DocumentLibraryItem[]>;

  downloadDocument?(
    documentId: string,
    defaultFileName?: string,
  ): Promise<{ blob: Blob; fileName: string }>;
  renderStructuredModel?(
    model: DiagramModelSpec | DesignDiagramModelSpec,
    stage: "feasibility" | "requirements" | "design",
  ): Promise<RenderStructuredModelResponse>;
  saveRequirementModelEdit?(
    diagramKind: DiagramType,
    model: DiagramModelSpec,
    status: ManualModelEditStatus,
    traceability?: Pick<
      WorkspaceRecord,
      "requirementModelTraceability" | "designModelTraceability"
    >,
  ): Promise<void>;
  saveDesignModelEdit?(
    modelId: string,
    model: DesignDiagramModelSpec,
    status: ManualModelEditStatus,
    traceability?: Pick<WorkspaceRecord, "designModelTraceability">,
  ): Promise<void>;
  saveManualModelRerender?(
    key: string,
    status: ManualModelEditStatus,
    artifact: {
      plantUmlSource: string;
      svgArtifact: SvgArtifact | DesignSvgArtifact;
    },
  ): Promise<void>;

  saveRunHistory(
    snapshot: RunHistorySnapshot,
    meta: { providerModel: string; durationMs?: number },
  ): Promise<RunHistoryItem>;
  listRunHistory(options?: { maxAgeMs?: number }): Promise<RunHistoryItem[]>;

  deleteRunHistory(id: string): Promise<RunHistoryItem[]>;

}

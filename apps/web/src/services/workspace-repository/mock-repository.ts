// Hosts the in-memory workspace repository used by tests and local flows without touching the HTTP adapter.
import {
  designRecordBelongsToDiagramKinds,
  designTraceabilityTouchesDiagramKinds,
  modelRecordBelongsToDiagramKinds,
  resolveModelArtifactIdentity,
  
  type DesignRunSnapshot,
  type DesignSvgArtifact,
  type DocumentLibraryItem,
  type DocumentRunSnapshot,
  type RequirementBaseline,
  type RunSnapshot,
  type SvgArtifact,
} from "@uml-platform/contracts";
import {
  getRequirementModelId,
  type DesignDiagramType,
  type DiagramType,
} from "../../entities/diagram/model";
import type { WorkspaceRecord } from "../../entities/workspace/model";
import type { RequirementRule } from "../../entities/requirement-rule/model";
import {
  clearRunHistoryItems,
  deleteRunHistoryItem,
  loadRunHistory,
  saveRunHistoryItem,
} from "../../entities/run-history";
import { documentFileName } from "./document-api";
import type {
  
  StartDesignRunInput,
  StartDocumentRunInput,
  StartRunInput,
} from "./start-inputs";
import {
  applySnapshotToWorkspace,
  createEmptyWorkspace,
} from "./workspace-state";
import type {
  RequirementRulesUpdateMetadata,
  WorkspaceRepository,
} from "./types";

export function createMockWorkspaceRepository(
  seed: Partial<WorkspaceRecord> = {},
  snapshotFactory?: (input: StartRunInput, runId: string) => RunSnapshot,
): WorkspaceRepository {
  const defaultWorkspace = createEmptyWorkspace();
  let workspace: WorkspaceRecord = {
    ...defaultWorkspace,
    ...seed,
    models: { ...defaultWorkspace.models, ...seed.models },
    requirementModelTraceability: seed.requirementModelTraceability
      ? [...seed.requirementModelTraceability]
      : [],
    plantUml: { ...defaultWorkspace.plantUml, ...seed.plantUml },
    svgArtifacts: { ...defaultWorkspace.svgArtifacts, ...seed.svgArtifacts },
    requirementInputFingerprint:
      seed.requirementInputFingerprint ??
      defaultWorkspace.requirementInputFingerprint,
    requirementReviewCandidates: {
      ...defaultWorkspace.requirementReviewCandidates,
      ...seed.requirementReviewCandidates,
    },
    autoGeneratedUpstreamReviews: {
      ...defaultWorkspace.autoGeneratedUpstreamReviews,
      ...seed.autoGeneratedUpstreamReviews,
    },
    diagramInputFingerprints: {
      ...defaultWorkspace.diagramInputFingerprints,
      ...seed.diagramInputFingerprints,
    },
    diagramVersions: {
      ...defaultWorkspace.diagramVersions,
      ...seed.diagramVersions,
    },
    designModels: { ...defaultWorkspace.designModels, ...seed.designModels },
    designModelTraceability: seed.designModelTraceability
      ? [...seed.designModelTraceability]
      : [],
    designPlantUml: {
      ...defaultWorkspace.designPlantUml,
      ...seed.designPlantUml,
    },
    designSvgArtifacts: {
      ...defaultWorkspace.designSvgArtifacts,
      ...seed.designSvgArtifacts,
    },
    designInputFingerprints: {
      ...defaultWorkspace.designInputFingerprints,
      ...seed.designInputFingerprints,
    },
    rules: seed.rules ? [...seed.rules] : [],
    selectedDiagramTypes: seed.selectedDiagramTypes
      ? [...seed.selectedDiagramTypes]
      : [],
    generatedDiagramTypes: seed.generatedDiagramTypes
      ? [...seed.generatedDiagramTypes]
      : [],
    diagramErrors: { ...defaultWorkspace.diagramErrors, ...seed.diagramErrors },
    selectedDesignDiagramTypes: seed.selectedDesignDiagramTypes
      ? [...seed.selectedDesignDiagramTypes]
      : [],
    generatedDesignDiagramTypes: seed.generatedDesignDiagramTypes
      ? [...seed.generatedDesignDiagramTypes]
      : [],
    designDiagramErrors: {
      ...defaultWorkspace.designDiagramErrors,
      ...seed.designDiagramErrors,
    },
    manualModelEditStatus: {
      ...defaultWorkspace.manualModelEditStatus,
      ...seed.manualModelEditStatus,
    },
    
    
    
  };
  const snapshots = new Map<string, RunSnapshot>();
  const designSnapshots = new Map<string, DesignRunSnapshot>();
  const documentSnapshots = new Map<string, DocumentRunSnapshot>();
  const documentBuffers = new Map<string, Blob>();
  const documents = new Map<string, DocumentLibraryItem>();

  return {
    async getProjectAccess() {
      return { capabilities: ["update_project", "start_runs"], generationExecutionMode: "offline-demo" };
    },
    async loadWorkspace() {
      return {
        ...workspace,
        rules: [...workspace.rules],
        selectedDiagramTypes: [...workspace.selectedDiagramTypes],
        generatedDiagramTypes: [...workspace.generatedDiagramTypes],
        models: { ...workspace.models },
        requirementModelTraceability: [
          ...workspace.requirementModelTraceability,
        ],
        plantUml: { ...workspace.plantUml },
        svgArtifacts: { ...workspace.svgArtifacts },
        diagramErrors: { ...workspace.diagramErrors },
        selectedDesignDiagramTypes: [...workspace.selectedDesignDiagramTypes],
        generatedDesignDiagramTypes: [...workspace.generatedDesignDiagramTypes],
        designModels: { ...workspace.designModels },
        designModelTraceability: [...workspace.designModelTraceability],
        designPlantUml: { ...workspace.designPlantUml },
        designSvgArtifacts: { ...workspace.designSvgArtifacts },
        designDiagramErrors: { ...workspace.designDiagramErrors },
        manualModelEditStatus: { ...workspace.manualModelEditStatus },
        
        
        
        
        
        
        
        
        
        
        
        
        requirementReviewCandidates: {
          ...workspace.requirementReviewCandidates,
        },
        requirementInputFingerprint: workspace.requirementInputFingerprint,
        diagramInputFingerprints: { ...workspace.diagramInputFingerprints },
        designInputFingerprints: { ...workspace.designInputFingerprints },
        rulesVersion: workspace.rulesVersion,
        rulesBasedOnTextVersion: workspace.rulesBasedOnTextVersion,
        diagramVersions: { ...workspace.diagramVersions },
      };
    },

    async updateRequirementText(text: string) {
      workspace = {
        ...workspace,
        requirementText: text,
      };
    },

    async updateRequirementRules(
      rules: RequirementRule[],
      metadata?: RequirementRulesUpdateMetadata,
    ) {
      workspace = {
        ...workspace,
        rules: [...rules],
        requirementInputFingerprint:
          "requirementInputFingerprint" in (metadata ?? {})
            ? (metadata?.requirementInputFingerprint ?? null)
            : workspace.requirementInputFingerprint,
        requirementBaseline:
          "requirementBaseline" in (metadata ?? {})
            ? metadata?.requirementBaseline === null ||
              metadata?.requirementBaseline === undefined
              ? null
              : (structuredClone(
                  metadata.requirementBaseline,
                ) as WorkspaceRecord["requirementBaseline"])
            : workspace.requirementBaseline,
        requirementQualityReport:
          "requirementBaseline" in (metadata ?? {})
            ? (metadata?.requirementQualityReport ??
              metadata?.requirementBaseline?.qualityReport ??
              null)
            : "requirementQualityReport" in (metadata ?? {})
              ? (metadata?.requirementQualityReport ?? null)
              : workspace.requirementQualityReport,
        requirementModelTraceability:
          "requirementModelTraceability" in (metadata ?? {})
            ? (structuredClone(
                metadata?.requirementModelTraceability ?? [],
              ) as WorkspaceRecord["requirementModelTraceability"])
            : workspace.requirementModelTraceability,
        requirementReviewCandidates:
          "requirementReviewCandidates" in (metadata ?? {})
            ? (structuredClone(
                metadata?.requirementReviewCandidates ?? {},
              ) as WorkspaceRecord["requirementReviewCandidates"])
            : workspace.requirementReviewCandidates,
        rulesBasedOnTextVersion:
          "rulesBasedOnTextVersion" in (metadata ?? {})
            ? (metadata?.rulesBasedOnTextVersion ?? null)
            : workspace.rulesBasedOnTextVersion,
        rulesVersion:
          typeof metadata?.rulesVersion === "number"
            ? metadata.rulesVersion
            : workspace.rulesVersion,
      };
    },

    async updateFeasibility(patch) {
      workspace = {
        ...workspace,
        feasibilityInputs: patch.inputs ?? workspace.feasibilityInputs,
        feasibilityContextModel: patch.contextModel === undefined ? workspace.feasibilityContextModel : patch.contextModel,
        feasibilityContextTraceability: patch.contextTraceability ?? workspace.feasibilityContextTraceability,
        feasibilityContextPlantUml: patch.contextPlantUml ?? workspace.feasibilityContextPlantUml,
        feasibilityContextSvg: patch.contextSvg ?? workspace.feasibilityContextSvg,
        visualReviews: patch.contextSvg === undefined ? workspace.visualReviews : Object.fromEntries(Object.entries(workspace.visualReviews ?? {}).filter(([key]) => !key.startsWith("feasibility:"))),
        feasibilityContextFingerprint: patch.contextFingerprint === undefined ? workspace.feasibilityContextFingerprint : patch.contextFingerprint,
        feasibilityImplementationPlan: patch.implementationPlan === undefined ? workspace.feasibilityImplementationPlan : patch.implementationPlan,
        feasibilityImplementationFingerprint: patch.implementationFingerprint === undefined ? workspace.feasibilityImplementationFingerprint : patch.implementationFingerprint,
      };
    },

    async updateRequirementBaseline(baseline: RequirementBaseline) {
      const nextBaseline = structuredClone(baseline) as RequirementBaseline;
      workspace = {
        ...workspace,
        requirementBaseline: nextBaseline,
        requirementQualityReport: nextBaseline.qualityReport,
      };
    },

    async updateRequirementReviewCandidates(candidates) {
      workspace = {
        ...workspace,
        requirementReviewCandidates: structuredClone(
          candidates,
        ) as WorkspaceRecord["requirementReviewCandidates"],
      };
    },

    async updateAutoGeneratedUpstreamReviews(reviews) {
      workspace = {
        ...workspace,
        autoGeneratedUpstreamReviews: structuredClone(
          reviews,
        ) as WorkspaceRecord["autoGeneratedUpstreamReviews"],
      };
    },

    

    async updateTestGenerationResult(result) {
      workspace = {
        ...workspace,
        testGenerationResult: result ? structuredClone(result) : null,
      };
    },

    async updateRequirementReviewState(baseline, candidates) {
      const nextBaseline = structuredClone(baseline) as RequirementBaseline;
      workspace = {
        ...workspace,
        requirementBaseline: nextBaseline,
        requirementQualityReport: nextBaseline.qualityReport,
        requirementReviewCandidates: structuredClone(
          candidates,
        ) as WorkspaceRecord["requirementReviewCandidates"],
      };
    },

    async repairRequirementRule() {
      throw new Error("当前环境不支持单项智能修复");
    },

    async repairRequirementRules() {
      throw new Error("当前环境不支持批量智能修复");
    },

    async startRun(input: StartRunInput) {
      const runId = `run-${Math.random().toString(36).slice(2, 10)}`;
      const snapshot = snapshotFactory?.(input, runId) ?? {
        runId,
        requirementText: input.requirementText,
        selectedDiagrams: input.selectedDiagrams,
        analysisTargetUseCaseIds: input.analysisTargetUseCaseIds ?? [],
        rules:
          input.rules.length > 0
            ? input.rules
            : (workspace.rules as RequirementRule[]),
        models: Object.values(workspace.models),
        requirementModelTraceability: [
          ...workspace.requirementModelTraceability,
        ],
        plantUml: Object.entries(workspace.plantUml).map(
          ([artifactId, source]) => {
            const identity = resolveModelArtifactIdentity(artifactId, workspace.models, workspace.svgArtifacts);
            return { ...identity, diagramKind: identity.diagramKind as DiagramType, source };
          },
        ),
        svgArtifacts: Object.values(workspace.svgArtifacts),
        diagramErrors: workspace.diagramErrors,
        requirementTrace: [],
        requirementBaseline: workspace.requirementBaseline,
        coverageMatrix: null,
        traceabilityMatrix: null,
        visualReviews: workspace.visualReviews,
        currentStage: "render_svg",
        status: "completed",
        error: null,
      };
      snapshots.set(runId, snapshot);
      return { runId };
    },

    async startDesignRun(input: StartDesignRunInput) {
      const runId = `design-run-${Math.random().toString(36).slice(2, 10)}`;
      const replacingDiagrams = Array.from(
        new Set([
          ...input.selectedDiagrams,
          ...(input.requestedDiagrams ?? []),
        ]),
      );
      const existingDesignModels = Object.entries(workspace.designModels)
        .filter(
          ([modelId, model]) =>
            !designRecordBelongsToDiagramKinds(
              modelId,
              model,
              replacingDiagrams,
            ),
        )
        .map(([, model]) => model);
      const existingDesignPlantUml = Object.entries(workspace.designPlantUml)
        .filter(
          ([artifactId, source]) =>
            !modelRecordBelongsToDiagramKinds(
              artifactId,
              { modelId: artifactId, source },
              replacingDiagrams,
              workspace.designModels,
            ),
        )
        .map(([artifactId, source]) => {
          const identity = resolveModelArtifactIdentity(artifactId, workspace.designModels, workspace.designSvgArtifacts);
          return {
            ...identity,
            diagramKind: identity.diagramKind as DesignDiagramType,
            source,
          };
        });
      const snapshot: DesignRunSnapshot = {
        runId,
        requirementText: "",
        selectedDiagrams: input.selectedDiagrams,
        requestedDiagrams: input.requestedDiagrams,
        rules: [],
        requirementBaseline: input.requirementBaseline,
        requirementModels: input.requirementModels,
        requirementModelTraceability: input.requirementModelTraceability,
        models: existingDesignModels,
        designModelTraceability: workspace.designModelTraceability.filter(
          (entry) =>
            !designTraceabilityTouchesDiagramKinds(entry, replacingDiagrams),
        ),
        plantUml: existingDesignPlantUml,
        svgArtifacts: Object.entries(workspace.designSvgArtifacts)
          .filter(
            ([artifactId, artifact]) =>
              !designRecordBelongsToDiagramKinds(
                artifactId,
                artifact,
                replacingDiagrams,
              ),
          )
          .map(([, artifact]) => artifact),
        diagramErrors: workspace.designDiagramErrors,
        designTrace: [],
        coverageMatrix: null,
        traceabilityMatrix: null,
        visualReviews: workspace.visualReviews,
        currentStage: "render_svg",
        status: "completed",
        error: null,
      };
      designSnapshots.set(runId, snapshot);
      return { runId };
    },

    

    async startDocumentRun(input: StartDocumentRunInput) {
      const runId = `document-run-${Math.random().toString(36).slice(2, 10)}`;
      const fileName = documentFileName(input.documentKind);
      const documentId = `doc-${input.documentKind}-${Math.random().toString(36).slice(2, 10)}`;
      const snapshot: DocumentRunSnapshot = {
        runId,
        documentKind: input.documentKind,
        requirementText: input.requirementText,
        requirementBaseline: workspace.requirementBaseline,
        coverageMatrix: null,
        traceabilityMatrix: null,
        feasibilityImplementationPlan: workspace.feasibilityImplementationPlan,
        feasibilityInputs: workspace.feasibilityInputs,
        documentId,
        sections: [
          { level: 1, title: "1 引言", body: ["Mock 说明书正文。"] },
          {
            level: 2,
            title: "1.1 编写目的",
            body: ["用于验证说明书生成流程。"],
          },
          { level: 3, title: "1.1.1 范围", body: ["当前为 Mock 快照。"] },
        ],
        fileName,
        mimeType:
          "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        byteLength: 12,
        missingArtifacts: [],
        currentStage: "render_document_file",
        status: "completed",
        error: null,
      };
      const now = new Date().toISOString();
      documents.set(documentId, {
        id: documentId,
        status: "active",
        workspaceId: "mock-workspace",
        documentKind: input.documentKind,
        title:
          input.documentKind === "requirementsSpec"
            ? "需求规格说明书"
            : input.documentKind === "softwareDesignSpec"
              ? "软件设计说明书"
              : "可行性研究报告",
        fileName,
        mimeType: snapshot.mimeType ?? "application/octet-stream",
        byteLength: snapshot.byteLength,
        version: 1,
        sourceRunId: runId,
        createdAt: now,
        updatedAt: now,
      });
      documentSnapshots.set(runId, snapshot);
      documentBuffers.set(
        runId,
        new Blob(["mock document"], {
          type: snapshot.mimeType ?? "application/octet-stream",
        }),
      );
      return { runId };
    },

    async subscribeToRun(runId, onEvent) {
      const snapshot = snapshots.get(runId);
      if (!snapshot) {
        throw new Error("Mock run not found");
      }
      onEvent({ type: "queued" });
      if (snapshot.rules.length > 0) {
        onEvent({
          type: "stage_started",
          stage: "extract_rules",
        });
      }
      onEvent({ type: "completed", snapshot });
    },

    

    async subscribeToDocumentRun(runId, onEvent) {
      const snapshot = documentSnapshots.get(runId);
      if (!snapshot) {
        throw new Error("Mock document run not found");
      }
      onEvent({ type: "queued" });
      onEvent({ type: "stage_started", stage: "generate_document_text" });
      onEvent({
        type: "stage_progress",
        stage: "generate_document_text",
        progress: 55,
        message: "正在生成说明书正文",
      });
      onEvent({ type: "stage_started", stage: "render_document_file" });
      onEvent({
        type: "artifact_ready",
        stage: "render_document_file",
        artifactKind: "document",
      });
      onEvent({ type: "completed", snapshot });
    },

    async subscribeToDesignRun(runId, onEvent) {
      const snapshot = designSnapshots.get(runId);
      if (!snapshot) {
        throw new Error("Mock design run not found");
      }
      onEvent({ type: "queued" });
      onEvent({
        type: "stage_started",
        stage: "generate_design_sequence",
      });
      onEvent({ type: "completed", snapshot });
    },

    async getRunSnapshot(runId) {
      const snapshot = snapshots.get(runId);
      if (!snapshot) {
        throw new Error("Mock run not found");
      }
      workspace = applySnapshotToWorkspace(workspace, snapshot);
      return snapshot;
    },

    async getDesignRunSnapshot(runId) {
      const snapshot = designSnapshots.get(runId);
      if (!snapshot) {
        throw new Error("Mock design run not found");
      }
      workspace = applySnapshotToWorkspace(workspace, snapshot);
      return snapshot;
    },

    

    async getDocumentRunSnapshot(runId) {
      const snapshot = documentSnapshots.get(runId);
      if (!snapshot) {
        throw new Error("Mock document run not found");
      }
      return snapshot;
    },

    async listDocuments() {
      return Array.from(documents.values()).sort((left, right) =>
        right.updatedAt.localeCompare(left.updatedAt),
      );
    },

    async getOnlyOfficeEditorConfig(documentId, uiTheme = "theme-dark") {
      const document = documents.get(documentId);
      if (!document) {
        throw new Error("Mock document not found");
      }
      return {
        document,
        documentServerUrl: "http://127.0.0.1:8080",
        config: {
          documentType: "word",
          document: {
            fileType: "docx",
            key: `${document.id}-v${document.version}`,
            title: document.fileName,
            url: `/api/documents/${document.id}/file`,
          },
          editorConfig: {
            callbackUrl: `/api/documents/${document.id}/onlyoffice/callback`,
            mode: "edit",
            lang: "zh-CN",
            customization: {
              uiTheme,
            },
          },
        },
      };
    },

    async downloadDocumentRun(runId, defaultFileName) {
      const snapshot = documentSnapshots.get(runId);
      const blob = documentBuffers.get(runId);
      if (!snapshot || !blob) {
        throw new Error("Mock document file not found");
      }
      return {
        blob,
        fileName: snapshot.fileName ?? defaultFileName ?? "说明书.docx",
      };
    },

    async downloadDocument(documentId, defaultFileName) {
      const document = documents.get(documentId);
      const runId = document?.sourceRunId;
      const blob = runId ? documentBuffers.get(runId) : null;
      if (!document || !blob) {
        throw new Error("Mock document file not found");
      }
      return {
        blob,
        fileName: document.fileName ?? defaultFileName ?? "说明书.docx",
      };
    },

    async renderPlantUml(diagramKind, plantUmlSource) {
      return {
        svg: `<svg><text>${diagramKind}</text></svg>`,
        renderMeta: {
          engine: "plantuml",
          generatedAt: new Date().toISOString(),
          sourceLength: plantUmlSource.length,
          durationMs: 1,
        },
      };
    },

    async renderStructuredModel(model) {
      const source = `@startuml\n' ${model.title}\n@enduml`;
      return {
        plantUmlSource: source,
        svg: `<svg><text>${model.diagramKind}</text></svg>`,
        renderMeta: {
          engine: "plantuml",
          generatedAt: new Date().toISOString(),
          sourceLength: source.length,
          durationMs: 1,
        },
      };
    },

    async confirmVisualReview(key, checkedAt) {
      const review = workspace.visualReviews?.[key];
      if (!review || review.status !== "pending_review" || review.checkedAt !== checkedAt) {
        throw new Error("视觉检查结果已更新，请刷新后重试。");
      }
      const confirmed = { ...review, confirmedAt: review.confirmedAt ?? new Date().toISOString() };
      workspace = { ...workspace, visualReviews: { ...workspace.visualReviews, [key]: confirmed } };
      return confirmed;
    },

    async saveRequirementModelEdit(_diagramKind, model, status, traceability) {
      const modelKey = getRequirementModelId(model);
      workspace = {
        ...workspace,
        models: { ...workspace.models, [modelKey]: model },
        ...(traceability
          ? {
              requirementModelTraceability:
                traceability.requirementModelTraceability,
              designModelTraceability: traceability.designModelTraceability,
            }
          : {}),
        manualModelEditStatus: {
          ...workspace.manualModelEditStatus,
          [modelKey]: status,
        },
      };
    },

    async saveDesignModelEdit(modelId, model, status, traceability) {
      workspace = {
        ...workspace,
        designModels: { ...workspace.designModels, [modelId]: model },
        ...(traceability
          ? { designModelTraceability: traceability.designModelTraceability }
          : {}),
        manualModelEditStatus: {
          ...workspace.manualModelEditStatus,
          [modelId]: status,
        },
      };
    },

    async saveManualModelRerender(key, status, artifact) {
      const isDesign = key in workspace.designModels;
      workspace = {
        ...workspace,
        visualReviews: Object.fromEntries(Object.entries(workspace.visualReviews ?? {}).filter(([reviewKey]) => reviewKey !== `${isDesign ? "design" : "requirements"}:${key}`)),
        manualModelEditStatus: {
          ...workspace.manualModelEditStatus,
          [key]: status,
        },
        ...(isDesign
          ? {
              designPlantUml: {
                ...workspace.designPlantUml,
                [key]: artifact.plantUmlSource,
              },
              designSvgArtifacts: {
                ...workspace.designSvgArtifacts,
                [key]: artifact.svgArtifact as DesignSvgArtifact,
              },
            }
          : {
              plantUml: {
                ...workspace.plantUml,
                [key]: artifact.plantUmlSource,
              },
              svgArtifacts: {
                ...workspace.svgArtifacts,
                [key]: artifact.svgArtifact as SvgArtifact,
              },
            }),
      };
    },

    async testProviderSettings() {
      return {
        ok: true,
        message: "Provider connection ok",
        capability: {
          structuredOutputMode: "strict_json",
          supportsJsonSchema: true,
          supportsJsonObject: true,
          modeLabel: "严格 JSON",
        },
      };
    },

    async saveRunHistory(snapshot, meta) {
      return saveRunHistoryItem(snapshot, meta);
    },

    async listRunHistory() {
      return loadRunHistory();
    },

    async getRunHistoryItem(id) {
      return loadRunHistory().find((item) => item.id === id) ?? null;
    },

    async restoreRunHistory(id) {
      return loadRunHistory().find((item) => item.id === id) ?? null;
    },

    async deleteRunHistory(id) {
      return deleteRunHistoryItem(id);
    },

    async clearRunHistory() {
      clearRunHistoryItems();
    },
  };
}

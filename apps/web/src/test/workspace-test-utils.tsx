export function withWorkspaceProviders(
  children: ReactNode,
  repository?: WorkspaceRepository,
) {
  if (!localStorage.getItem(USER_SETTINGS_STORAGE_KEY)) {
    localStorage.setItem(
      USER_SETTINGS_STORAGE_KEY,
      JSON.stringify(DEFAULT_USER_SETTINGS),
    );
  }

  return (
    <AppI18nProvider>
      <ThemeProvider>
        <FeedbackDialogProvider>
          <WorkspaceShellProvider>
            <WorkspaceRepositoryProvider repository={repository}>
              <WorkspaceSessionProvider><SidebarProvider><TooltipProvider>{children}</TooltipProvider></SidebarProvider></WorkspaceSessionProvider>
            </WorkspaceRepositoryProvider>
          </WorkspaceShellProvider>
        </FeedbackDialogProvider>
      </ThemeProvider>
    </AppI18nProvider>
  );
}

